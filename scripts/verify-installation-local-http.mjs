import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";

// Real local HTTP routes/auth/operations, synthetic persistence only. No SQL.
const app = "http://127.0.0.1:3045", fixture = "http://127.0.0.1:45435";
const id = "11111111-1111-4111-8111-111111111111";
const evidence = [];
const control = body => fetch(`${fixture}/__fixture/control`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
const state = async () => (await fetch(`${fixture}/__fixture/evidence`)).json();
const post = (path, body, cookie = "") => fetch(`${app}${path}`, { method: "POST", headers: { "Content-Type": "application/json", cookie }, body: JSON.stringify(body) });
await control({ reset: true, mode: "not_initialized" });
assert.equal((await post("/api/installations", {})).status, 503);
assert.equal((await post(`/api/installations/${id}/checkout`, { purpose: "balance" })).status, 503);
assert.equal((await post(`/api/admin/installations/${id}/cash`, {})).status, 401);
assert.equal((await state()).log.length, 0);
evidence.push("Disabled intake/checkout direct POSTs: 503, zero persistence requests; unauthorized cash POST: 401.");
const login = await post("/api/admin/reviews/login", { password: "synthetic-local-admin" });
assert.equal(login.status, 200);
const cookie = login.headers.get("set-cookie").split(";")[0];
const missing = await fetch(`${app}/api/admin/installations`, { headers: { cookie } });
assert.equal(missing.status, 503); assert.equal((await missing.json()).code, "installation_not_initialized");
evidence.push("Real shared-admin authentication retained; missing schema returns explicit not-initialized state.");
await control({ reset: true, mode: "normal" });
const receipt = { operationKey: "99999999-9999-4999-8999-999999999999", amountDollars: "50.00", receivedAt: "2026-09-01T17:30:00.000Z", reference: "SYNTHETIC-HTTP", notes: "Synthetic HTTP verification", confirmOverpayment: false, actor: "must never be trusted" };
let response = await post(`/api/admin/installations/${id}/cash`, receipt, cookie);
assert.equal(response.status, 200); const first = await response.json(); assert.equal(first.balance.balanceDueCents, 70000);
response = await post(`/api/admin/installations/${id}/cash`, receipt, cookie);
const replay = await response.json(); assert.equal(response.status, 200); assert.equal(replay.paymentId, first.paymentId); assert.equal(replay.replayed, true);
assert.equal((await post(`/api/admin/installations/${id}/cash`, { ...receipt, notes: "conflict" }, cookie)).status, 409);
const recorded = await state();
assert.equal(recorded.state.installation_payments.filter(p => p.method === "cash").length, 1);
assert.equal(recorded.state.installation_audit_events.length, 1);
assert.equal(recorded.state.installations[0].payment_status, "partially_paid"); assert.equal(recorded.state.installations[0].status, "scheduled");
assert.equal(recorded.state.installation_payments[1].recorded_by, "IDS shared administrator");
evidence.push("Real cash POST: $50 yields $700 due and partial payment; replay preserves one receipt/audit; conflicting key is 409; browser-supplied actor ignored.");
const overpay = { ...receipt, operationKey: "88888888-8888-4888-8888-888888888888", amountDollars: "800.00" };
assert.equal((await post(`/api/admin/installations/${id}/cash`, overpay, cookie)).status, 409);
response = await post(`/api/admin/installations/${id}/cash`, { ...overpay, confirmOverpayment: true }, cookie);
assert.equal(response.status, 200); assert.equal((await response.json()).balance.customerCreditCents, 10000);
evidence.push("Real cash POST: excess cash rejected without consent; confirmed excess is retained as customer credit.");
const customer = await (await fetch(`${app}/api/installations/${id}`)).json();
assert.equal(customer.controls.onlinePaymentsEnabled, false);
assert.ok(customer.payments.every(p => !("cash_operation_payload" in p) && !("notes" in p)));
evidence.push("Customer route uses effective disabled payment state and does not expose internal cash payload/notes.");
writeFileSync("docs/review/evidence/local-http-results.json", JSON.stringify({ scope: "Real local HTTP/auth/operation paths with mocked persistence. No SQL executed.", evidence }, null, 2) + "\n");
console.log(evidence.join("\n"));
await control({ reset: true, mode: "normal" });
